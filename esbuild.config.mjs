import esbuild from "esbuild";
import process from "node:process";
import { copyFileSync, readFileSync, writeFileSync } from "node:fs";
import builtins from "builtin-modules";

const prod = process.argv[2] === "production";

const shared = {
  bundle: true,
  external: ["obsidian", "electron", "@codemirror/*", ...builtins],
  format: "cjs",
  target: "es2020",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
};

// The Instructor Studio plugin reuses the same stylesheet (same tokens and
// classes); keep its copy in sync on every build.
const syncInstructorStyles = () => copyFileSync("styles.css", "instructor-plugin/styles.css");

// The main plugin carries the built Instructor Studio plugin inside its own
// bundle so one install surfaces both plugins (see src/companion-install.ts).
// This writes the gitignored payload module the main bundle imports, so the
// instructor build must land before the main build ever runs.
const generateCompanionPayload = () => {
  const embed = (path) => JSON.stringify(readFileSync(path, "utf8"));
  writeFileSync(
    "src/companion-payload.ts",
    `/**
 * companion-payload.ts — GENERATED by esbuild.config.mjs on every build.
 * Do not edit or commit (gitignored). The built KNOBE Instructor Studio
 * plugin, embedded so the main plugin can install it into the vault.
 */
export const COMPANION_MANIFEST_JSON: string = ${embed("instructor-plugin/manifest.json")};
export const COMPANION_MAIN_JS: string = ${embed("instructor-plugin/main.js")};
export const COMPANION_STYLES_CSS: string = ${embed("instructor-plugin/styles.css")};
`
  );
};

// Two independently-installable plugins built from one repo:
//   src/main.ts            -> main.js                     (KNOBE Studio)
//   src/instructor-main.ts -> instructor-plugin/main.js   (KNOBE Instructor Studio)
const instructorTarget = { entryPoints: ["src/instructor-main.ts"], outfile: "instructor-plugin/main.js" };
const mainTarget = { entryPoints: ["src/main.ts"], outfile: "main.js" };

const buildInstructorAndPayload = async () => {
  await esbuild.build({ ...shared, ...instructorTarget });
  syncInstructorStyles();
  generateCompanionPayload();
};

if (prod) {
  await buildInstructorAndPayload();
  await esbuild.build({ ...shared, ...mainTarget });
  process.exit(0);
} else {
  // Watch mode: regenerating the payload after each instructor rebuild
  // touches src/companion-payload.ts, which the main context watches — so the
  // embedded companion stays current during development too.
  await buildInstructorAndPayload();
  const instructorCtx = await esbuild.context({
    ...shared,
    ...instructorTarget,
    plugins: [
      {
        name: "companion-payload",
        setup(build) {
          build.onEnd((result) => {
            if (result.errors.length) return;
            syncInstructorStyles();
            generateCompanionPayload();
          });
        },
      },
    ],
  });
  const mainCtx = await esbuild.context({ ...shared, ...mainTarget });
  await instructorCtx.watch();
  await mainCtx.watch();
}
